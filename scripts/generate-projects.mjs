// Builds src/content/projects/index.js from every project file in that folder.
// Runs automatically before `npm run dev` and `npm run build`.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "src", "content", "projects");
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".js") && f !== "index.js" && !f.startsWith("_"))
  .sort();

const out = `// ⚠ AUTO-GENERATED by scripts/generate-projects.mjs — do not edit by hand.
// It lists every project file in this folder (files starting with "_" are skipped).
${files.map((f, i) => `import p${i} from "./${f.replace(/\.js$/, "")}";`).join("\n")}

const projects = [${files.map((_, i) => `p${i}`).join(", ")}];

export default projects;
`;

fs.writeFileSync(path.join(dir, "index.js"), out);
console.log(`✓ Projects: ${files.length} file(s) — ${files.join(", ")}`);
