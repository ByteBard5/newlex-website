// Builds src/content/projects/index.js from every project file in that folder.
// Runs before `npm run dev` and `npm run build`, and while the dev server is
// running next.config.mjs calls it again whenever a project file is added,
// renamed or deleted, so a new project shows up without restarting.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const projectsDir = path.join(process.cwd(), "src", "content", "projects");

export function generateProjects({ quiet = false } = {}) {
  const files = fs
    .readdirSync(projectsDir)
    .filter((f) => f.endsWith(".js") && f !== "index.js" && !f.startsWith("_"))
    .sort();

  const out = `// ⚠ AUTO-GENERATED by scripts/generate-projects.mjs — do not edit by hand.
// It lists every project file in this folder (files starting with "_" are skipped).
${files.map((f, i) => `import p${i} from "./${f.replace(/\.js$/, "")}";`).join("\n")}

const projects = [${files.map((_, i) => `p${i}`).join(", ")}];

export default projects;
`;

  const target = path.join(projectsDir, "index.js");
  // Only write when the list changed, so the dev server does not reload for nothing.
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== out) fs.writeFileSync(target, out);
  if (!quiet || current !== out) console.log(`✓ Projects: ${files.length} file(s) — ${files.join(", ")}`);
}

// Run directly: `npm run projects`
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateProjects();
}
